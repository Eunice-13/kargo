create table if not exists public.order_extension_requests (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  requested_at timestamptz not null default now()
);

create unique index if not exists order_extension_requests_order_requested_uidx
  on public.order_extension_requests (order_id, requested_at);

create index if not exists order_extension_requests_order_idx
  on public.order_extension_requests (order_id);

revoke all on table public.order_extension_requests from public, anon, authenticated;

insert into public.order_extension_requests (order_id, requested_at)
select o.id, n.created_at
from public.notifications n
join public.orders o on o.id::text = n.context ->> 'order_id'
where n.dedupe_key like 'extension_requested_%'
on conflict do nothing;

insert into public.order_extension_requests (order_id, requested_at)
select o.id, o.extension_requested_at
from public.orders o
where o.extension_requested_at is not null
  and not exists (
    select 1
    from public.notifications n
    where n.dedupe_key =
      'extension_requested_' || o.id::text || '_' ||
      extract(epoch from o.extension_requested_at)::bigint::text
  )
on conflict do nothing;

create or replace function public.track_order_extension_request()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  max_requests constant integer := 2;
  request_count bigint;
begin
  if new.extension_status = 'pending'
     and old.extension_status is distinct from 'pending' then
    select count(*) into request_count
    from public.order_extension_requests
    where order_id = new.id;

    if request_count >= max_requests then
      raise exception 'You''ve used all % extension requests for this claim.', max_requests;
    end if;

    insert into public.order_extension_requests (order_id, requested_at)
    values (new.id, coalesce(new.extension_requested_at, now()));
  end if;

  return new;
end;
$$;

revoke all on function public.track_order_extension_request() from public, anon, authenticated;

drop trigger if exists track_order_extension_request on public.orders;
create trigger track_order_extension_request
before update of extension_status on public.orders
for each row
execute function public.track_order_extension_request();

create or replace function public.my_order_extension_request_counts(p_order_id uuid default null)
returns table (order_id uuid, request_count bigint)
language sql
security definer
set search_path = ''
as $$
  select o.id, count(r.id)
  from public.orders o
  left join public.order_extension_requests r on r.order_id = o.id
  where o.buyer_id = auth.uid()
    and (p_order_id is null or o.id = p_order_id)
  group by o.id;
$$;

revoke all on function public.my_order_extension_request_counts(uuid) from public, anon;
grant execute on function public.my_order_extension_request_counts(uuid) to authenticated;
